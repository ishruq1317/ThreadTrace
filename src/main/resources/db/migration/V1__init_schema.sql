-- ThreadTrace Core Schema (PostgreSQL & H2 compatible standard SQL)

CREATE TABLE parties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    party_type VARCHAR(40) NOT NULL,
    country VARCHAR(100) NOT NULL,
    region VARCHAR(150) NOT NULL,
    exact_address VARCHAR(500),
    worker_count INTEGER,
    unit_price_usd NUMERIC(19, 4),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE production_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    factory_id BIGINT NOT NULL REFERENCES parties(id),
    process_type VARCHAR(64) NOT NULL,
    location_detail VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_code VARCHAR(80) NOT NULL UNIQUE,
    lot_type VARCHAR(40) NOT NULL,
    material_type VARCHAR(100) NOT NULL,
    style_code VARCHAR(80),
    brand_code VARCHAR(64) NOT NULL,
    supplier_id BIGINT REFERENCES parties(id),
    factory_id BIGINT REFERENCES parties(id),
    quantity NUMERIC(19, 4) NOT NULL,
    mass_kg NUMERIC(19, 4) NOT NULL,
    piece_count INTEGER NOT NULL DEFAULT 0,
    unit VARCHAR(24) NOT NULL,
    claimed_attribute VARCHAR(80),
    claimed_pct NUMERIC(7, 4) NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    orphan BOOLEAN NOT NULL DEFAULT FALSE,
    event_sequence BIGINT NOT NULL DEFAULT 0,
    latest_event_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_lots_brand ON lots(brand_code);
CREATE INDEX idx_lots_style ON lots(style_code);
CREATE INDEX idx_lots_status ON lots(status);

CREATE TABLE lot_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_code VARCHAR(80) NOT NULL UNIQUE,
    lot_id BIGINT NOT NULL REFERENCES lots(id),
    event_type VARCHAR(32) NOT NULL,
    process_step VARCHAR(64) NOT NULL,
    party_id BIGINT REFERENCES parties(id),
    production_line_id BIGINT REFERENCES production_lines(id),
    input_quantity NUMERIC(19, 4) NOT NULL,
    output_quantity NUMERIC(19, 4) NOT NULL,
    unit VARCHAR(24) NOT NULL,
    water_liters NUMERIC(19, 4) NOT NULL DEFAULT 0,
    energy_kwh NUMERIC(19, 4) NOT NULL DEFAULT 0,
    co2e_kg NUMERIC(19, 4) NOT NULL DEFAULT 0,
    corrects_event_id BIGINT REFERENCES lot_events(id),
    sequence_number BIGINT NOT NULL,
    previous_hash VARCHAR(64) NOT NULL,
    event_hash VARCHAR(64) NOT NULL,
    flagged BOOLEAN NOT NULL DEFAULT FALSE,
    flag_reason VARCHAR(500),
    notes VARCHAR(500),
    recorded_by VARCHAR(100) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_lot_events_lot_seq UNIQUE (lot_id, sequence_number)
);

CREATE INDEX idx_lot_events_lot ON lot_events(lot_id, sequence_number);
CREATE INDEX idx_lot_events_type ON lot_events(event_type);

CREATE TABLE lot_edges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES lot_events(id),
    parent_lot_id BIGINT NOT NULL REFERENCES lots(id),
    child_lot_id BIGINT NOT NULL REFERENCES lots(id),
    allocated_quantity NUMERIC(19, 4) NOT NULL,
    unit VARCHAR(24) NOT NULL,
    allocated_mass_kg NUMERIC(19, 4) NOT NULL,
    allocated_pieces INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_lot_edges_parent ON lot_edges(parent_lot_id, child_lot_id);
CREATE INDEX idx_lot_edges_child ON lot_edges(child_lot_id, parent_lot_id);

CREATE TABLE certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_number VARCHAR(100) NOT NULL UNIQUE,
    certificate_type VARCHAR(64) NOT NULL,
    issuer VARCHAR(200) NOT NULL,
    scope VARCHAR(200) NOT NULL,
    claimed_attribute VARCHAR(80),
    certified_pct NUMERIC(7, 4) NOT NULL DEFAULT 100,
    supplier_id BIGINT REFERENCES parties(id),
    lot_id BIGINT REFERENCES lots(id),
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    status VARCHAR(32) NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_certificates_supplier ON certificates(supplier_id);
CREATE INDEX idx_certificates_lot ON certificates(lot_id);
CREATE INDEX idx_certificates_valid_to ON certificates(valid_to, status);

CREATE TABLE compliance_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type VARCHAR(64) NOT NULL,
    severity VARCHAR(24) NOT NULL,
    brand_code VARCHAR(64),
    lot_id BIGINT REFERENCES lots(id),
    certificate_id BIGINT REFERENCES certificates(id),
    message VARCHAR(1000) NOT NULL,
    resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_compliance_alerts_lot ON compliance_alerts(lot_id);
CREATE INDEX idx_compliance_alerts_type ON compliance_alerts(alert_type, resolved);

CREATE TABLE product_passports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passport_code VARCHAR(80) NOT NULL,
    version INTEGER NOT NULL,
    latest_version BOOLEAN NOT NULL,
    style_code VARCHAR(80) NOT NULL,
    style_name VARCHAR(200) NOT NULL,
    shipment_lot_id BIGINT NOT NULL REFERENCES lots(id),
    brand_code VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    allocation_method VARCHAR(32) NOT NULL,
    payload_json TEXT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    etag VARCHAR(80) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_passport_code_version UNIQUE (passport_code, version)
);

CREATE INDEX idx_passports_code_latest ON product_passports(passport_code, latest_version);
CREATE INDEX idx_passports_shipment ON product_passports(shipment_lot_id);
CREATE INDEX idx_passports_brand ON product_passports(brand_code);

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code VARCHAR(80) NOT NULL UNIQUE,
    import_type VARCHAR(40) NOT NULL,
    file_format VARCHAR(20) NOT NULL,
    filename VARCHAR(255) NOT NULL,
    total_rows INTEGER NOT NULL DEFAULT 0,
    accepted_rows INTEGER NOT NULL DEFAULT 0,
    rejected_rows INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    uploaded_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE import_rejected_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES import_batches(id),
    row_number INTEGER NOT NULL,
    raw_payload TEXT NOT NULL,
    reason VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
